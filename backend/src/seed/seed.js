/** Parse the small, quoted CSV used for the faculty directory without another runtime dependency. */
function parseCsvLine(line) {
  const values = [];
  let value = '';
  let quoted = false;

  for (let index = 0; index < line.length; index += 1) {
    const character = line[index];
    if (character === '"') {
      if (quoted && line[index + 1] === '"') {
        value += '"';
        index += 1;
      } else {
        quoted = !quoted;
      }
    } else if (character === ',' && !quoted) {
      values.push(value.trim());
      value = '';
    } else {
      value += character;
    }
  }
  values.push(value.trim());
  return values;
}

function readFacultyCsv() {
  const [header, ...lines] = readFileSync(facultyCsvPath, 'utf8').trim().split(/\r?\n/);
  const columns = parseCsvLine(header);

  return lines.filter(Boolean).map((line) => {
    const values = parseCsvLine(line);
    return Object.fromEntries(columns.map((column, index) => [column, values[index] || '']));
  });
}

function departmentCode(name, usedCodes) {
  const aliases = {
    CSE: 'CSE',
    'Information Technology': 'IT',
    'Mechanical Engineering': 'MECH',
    'Civil Engineering': 'CIVIL',
  };
  if (aliases[name]) return aliases[name];
  const base = name.toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_|_$/g, '').slice(0, 18);
  let code = base || 'DEPT';
  let suffix = 2;
  while (usedCodes.has(code)) code = `${base.slice(0, 15)}_${suffix++}`;
  usedCodes.add(code);
  return code;
}

function campusDetailsFromCabin(cabin) {
  const match = /^([NS])(\d)(\d{2})$/i.exec(cabin.trim());
  if (!match) return { building: '', floor: '' };
  return {
    building: match[1].toUpperCase() === 'N' ? 'North Block' : 'South Block',
    floor: match[2],
  };
}

/** Create a small, real, downloadable placeholder file for a resource. */
async function makePlaceholderFile(title, type) {
  const content =
    `CampusOne — SAMPLE ${type.replace('_', ' ').toUpperCase()}\n` +
    `================================================\n\n` +
    `Title: ${title}\n\n` +
    `This is demo/sample content generated by the CampusOne seed script so that\n` +
    `download and preview features are fully functional during development and\n` +
    `demonstrations. Replace with real documents in production.\n`;
  const originalName = `${title.replace(/[^a-z0-9]+/gi, '_')}.txt`;
  const key = storage.buildKey('seed', originalName);
  const buffer = Buffer.from(content, 'utf8');
  const stored = await storage.putObject({
    buffer,
    key,
    mimeType: 'text/plain',
    size: buffer.length,
  });
  return { ...stored, originalName, mimeType: 'text/plain' };
}

